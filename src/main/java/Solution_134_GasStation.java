import java.util.Arrays;

public class Solution_134_GasStation {
    public static void main(String[] args) {
        var gas = new int[]{1, 2, 3, 4, 5};
        var cost = new int[]{3, 4, 5, 1, 2};
        canCompleteCircuit(gas, cost);
    }

    /**
     * Хитрое решение (жадный алгоритм)
     * Основано на двух простых мыслях:
     * -
     * Мысль 1. Проверка "а возможно ли вообще объехать?"
     * Если сложить всё топливо на всех заправках (sum(gas)) и вычесть все затраты на все перегоны (sum(cost)):
     * Если sum(gas) < sum(cost) → объехать нельзя никогда (хоть с какой заправки стартуй) → ответ -1.
     * Если sum(gas) >= sum(cost) → решение существует и единственно.
     * Второе утверждение — доказанный факт для этой задачи.
     * -
     * Мысль 2. Как найти эту единственную стартовую заправку за один проход?
     * Поедем с воображаемой заправки 0 и будем считать остаток топлива в баке в пути:
     * На заправке i доливаем gas[i], потом тратим cost[i] на переезд к i+1.
     * Если остаток когда-то стал отрицательным (не хватило доехать до следующей заправки), значит ни одна заправка от старта до текущей не может быть началом (потому что от любой из них в пути остаток станет отрицательным ещё раньше или в той же точке).
     * Значит, нужно начать со следующей заправки после провала, обнулить остаток в баке и продолжать проверку.
     */
    static int canCompleteCircuit(int[] gas, int[] cost) {
        var totalGas = Arrays.stream(gas).sum();
        var totalCost = Arrays.stream(cost).sum();
        // Если газа в сумме меньше, чем нужно затратить - невозможно объехать
        if (totalGas < totalCost) return -1;

        int startStation = 0;     // Потенциальная стартовая станция
        int currentTank = 0;      // Текущее топливо в баке

        // Проходим по всем станциям один раз
        for (int i = 0; i < gas.length; i++) {
            // Добавляем разницу между полученным и потраченным топливом
            currentTank += gas[i] - cost[i];
            // Если бак стал отрицательным - значит от текущего старта доехать нельзя
            if (currentTank < 0) {
                // Пробуем начать со следующей станции
                startStation = i + 1;
                // Обнуляем бак для новой попытки
                currentTank = 0;
            }
        }

        // Так как мы уже проверили, что totalGas >= totalCost,
        // то найденный startStation точно подходит
        return startStation;
    }
}
