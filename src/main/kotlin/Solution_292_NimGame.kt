/**
 * 1. Суть игры
 * Есть куча из n камней.
 *
 * Ты ходишь первым.
 * За один ход можно взять 1, 2 или 3 камня.
 * Выигрывает тот, кто берет последний камень.
 * Оба играют идеально (без ошибок).
 *
 * 2. Ключевое наблюдение — "проигрышная позиция"
 * В таких играх важно найти позиции, из которых невозможно выиграть при правильной игре соперника.
 * Давай посмотрим на маленькие числа:
 * n = 1 → Ты берешь 1 камень и выигрываешь. ✅ (выигрышная)
 * n = 2 → Ты берешь 2 камня и выигрываешь. ✅ (выигрышная)
 * n = 3 → Ты берешь 3 камня и выигрываешь. ✅ (выигрышная)
 * n = 4 → Что бы ты ни взял (1, 2 или 3), сопернику останется 3, 2 или 1 камень соответственно, и он их заберет и выиграет. ❌ (проигрышная)
 *
 * 3. Что дальше?
 * Теперь посмотрим, что происходит, если камней больше:
 * n = 5
 * Ты можешь взять 1 камень, оставив 4.
 * А 4 — это проигрышная позиция для того, чей ход. Соперник оказывается в проигрышной позиции → значит, ты выигрываешь. ✅
 * n = 6
 * Ты берешь 2 камня, оставляешь 4 → соперник проигрывает. ✅
 * n = 7
 * Ты берешь 3 камня, оставляешь 4 → соперник проигрывает. ✅
 * n = 8
 * Что бы ты ни взял (1, 2 или 3), сопернику достанется 7, 6 или 5 камней.
 * А мы только что выяснили, что 5, 6 и 7 — выигрышные позиции для того, кто ходит.
 * Значит, соперник окажется в выигрышной позиции и победит. ❌
 *
 * 4. Закономерность
 * Посмотрим на последовательность:
 *
 * n = 1 → выигрыш
 * n = 2 → выигрыш
 * n = 3 → выигрыш
 * n = 4 → проигрыш
 * n = 5 → выигрыш
 * n = 6 → выигрыш
 * n = 7 → выигрыш
 * n = 8 → проигрыш
 *
 * Видно, что проигрышные позиции повторяются каждые 4 числа:
 * 4, 8, 12, 16, ...
 *
 * То есть если количество камней делится на 4 без остатка, то первый игрок (ты) проигрывает при оптимальной игре.
 * Во всех остальных случаях — выигрывает.
 *
 * 5. Почему так?
 * Потому что соперник всегда может "добить" твой ход до 4.
 * Например:
 * Ты берешь 1 → соперник берет 3 (в сумме 4)
 * Ты берешь 2 → соперник берет 2 (в сумме 4)
 * Ты берешь 3 → соперник берет 1 (в сумме 4)
 *
 * Таким образом, если изначально камней кратно 4, соперник может после каждого твоего хода делать так, чтобы после его хода оставалось снова число, кратное 4, и в конце именно он возьмет последний камень.
 *
 * 6. Итоговое правило
 * Ты выигрываешь (ответ true), если n не делится на 4.
 * Ты проигрываешь (ответ false), если n делится на 4.
 *
 * Вот и все решение. Никаких сложных переборов — просто проверка остатка от деления на 4.
 */
fun canWinNim(n: Int): Boolean {
    return n % 4 != 0
}