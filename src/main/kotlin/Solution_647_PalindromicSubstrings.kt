/**
 * 647 Palindromic Substrings
 *
 * Medium
 *
 * Given a string s, return the number of palindromic substrings in it.
 *
 * A string is a palindrome when it reads the same backward as forward.
 *
 * A substring is a contiguous sequence of characters within the string.
 *
 *
 *
 * Example 1:
 *
 * Input: s = "abc"
 * Output: 3
 * Explanation: Three palindromic strings: "a", "b", "c".
 * Example 2:
 *
 * Input: s = "aaa"
 * Output: 6
 * Explanation: Six palindromic strings: "a", "a", "a", "aa", "aa", "aaa".
 *
 *
 * Constraints:
 *
 * 1 <= s.length <= 1000
 * s consists of lowercase English letters.
 */
fun main() {
    val s = "aaa"
    countSubstrings(s)
}

/**
 * Ключевая идея
 * Вместо того чтобы проверять все возможные подстроки (их O(n²)), мы можем использовать свойство палиндромов: каждый палиндром имеет центр, от которого он "расширяется" в обе стороны.
 *
 * Что такое центр?
 * Центр палиндрома может быть:
 *
 * Одиночный символ — для палиндромов нечетной длины (например, "aba" имеет центр в 'b')
 * Пара одинаковых символов — для палиндромов четной длины (например, "abba" имеет центр между двумя 'b')
 *
 * Логика решения
 * Шаг 1: Перебираем все возможные центры
 * Для строки длины n:
 *
 * Одиночных центров: n (каждый символ)
 * Парных центров: n-1 (между каждой парой соседних символов)
 * Всего центров: 2n - 1
 *
 * Шаг 2: Расширяемся от каждого центра
 * Для каждого центра мы делаем следующее:
 *
 * Устанавливаем левый и правый указатели на центр
 * Пока указатели в пределах строки и символы слева и справа совпадают:
 *
 * Мы нашли новый палиндром → увеличиваем счетчик
 *
 * Расширяемся: двигаем левый указатель влево, правый — вправо
 * Как только символы не совпали или вышли за границы — останавливаемся
 *
 * Важный нюанс: два типа центров
 * Для нечетных палиндромов (центр — символ):
 *
 * Начинаем: left = i, right = i
 * Проверяем s[left] == s[right]
 * Расширяемся: left--, right++
 *
 * Для четных палиндромов (центр — между символами):
 * Начинаем: left = i, right = i + 1
 * Проверяем s[left] == s[right]
 * Расширяемся: left--, right++
 *
 * Почему это работает?
 * Каждый палиндром имеет ровно один центр (либо символ, либо промежуток между символами). Расширяясь от центра, мы найдем все палиндромы, и каждый ровно один раз.
 */
fun countSubstrings(s: String): Int {
    var count = 0
    val n = s.length

    // Перебираем все возможные центры
    for (i in 0 until n) {
        // Случай 1: нечетные палиндромы (центр - одиночный символ)
        count += expandAroundCenter(s, i, i)

        // Случай 2: четные палиндромы (центр - между двумя символами)
        if (i < n - 1) {
            count += expandAroundCenter(s, i, i + 1)
        }
    }

    return count
}

// Функция расширения от центра
// Возвращает количество палиндромов, найденных при расширении от данного центра
private fun expandAroundCenter(s: String, left: Int, right: Int): Int {
    var count = 0
    var l = left
    var r = right

    // Расширяемся, пока не вышли за границы и символы совпадают
    while (l >= 0 && r < s.length && s[l] == s[r]) {
        count++ // Нашли новый палиндром
        l-- // Расширяемся влево
        r++ // Расширяемся вправо
    }

    return count
}