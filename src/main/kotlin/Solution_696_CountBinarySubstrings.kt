import kotlin.math.min

/**
 * 696 Count Binary Substrings
 *
 * Easy
 *
 * Given a binary string s, return the number of non-empty substrings that have the same number of 0's and 1's, and all the 0's and all the 1's in these substrings are grouped consecutively.
 *
 * Substrings that occur multiple times are counted the number of times they occur.
 *
 *
 *
 * Example 1:
 *
 * Input: s = "00110011"
 * Output: 6
 * Explanation: There are 6 substrings that have equal number of consecutive 1's and 0's: "0011", "01", "1100", "10", "0011", and "01".
 * Notice that some of these substrings repeat and are counted the number of times they occur.
 * Also, "00110011" is not a valid substring because all the 0's (and 1's) are not grouped together.
 * Example 2:
 *
 * Input: s = "10101"
 * Output: 4
 * Explanation: There are 4 substrings: "10", "01", "10", "01" that have equal number of consecutive 1's and 0's.
 *
 *
 * Constraints:
 *
 * 1 <= s.length <= 105
 * s[i] is either '0' or '1'.
 */
fun main() {
    val s = "00110011";
    countBinarySubstrings(s);
}

/**
 * Суть задачи
 * Нам нужно найти подстроки, где:
 * Количество нулей и единиц равно
 * Все нули и все единицы идут подряд (группами)
 * Это значит, что допустимые подстроки имеют вид:
 * 00...011...1 (сначала все нули, потом все единицы)
 * 11...100...0 (сначала все единицы, потом все нули)
 * И количество нулей должно равняться количеству единиц.
 * <p>
 * Ключевая идея
 * Вместо того чтобы перебирать все подстроки (это O(n²), что слишком медленно для n ≤ 10⁵), мы можем использовать группировку.
 * <p>
 * Шаг 1: Группируем одинаковые символы
 * Разбиваем строку на группы подряд идущих одинаковых символов и запоминаем длины этих групп.
 * Пример: s = "00110011"
 * Группы: "00" (длина 2), "11" (длина 2), "00" (длина 2), "11" (длина 2)
 * Длины групп: [2, 2, 2, 2]
 * <p>
 * Шаг 2: Анализируем соседние группы
 * Для каждой пары соседних групп (одна из нулей, другая из единиц) мы можем образовать подстроки.
 * Сколько подстрок можно получить из двух соседних групп?
 * Возьмем группы с длинами a и b. Мы можем брать:
 * 1 ноль и 1 единицу → "01" или "10"
 * 2 нуля и 2 единицы → "0011" или "1100"
 * ...
 * min(a, b) нулей и min(a, b) единиц
 * То есть количество подстрок = min(a, b)
 * <p>
 * Шаг 3: Суммируем
 * Складываем min(a, b) для всех соседних пар групп.
 * Разбор примеров
 * <p>
 * Пример 1: s = "00110011"
 * Группы: [2, 2, 2, 2]
 * Соседние пары:
 * Группа 1 и 2: min(2, 2) = 2 → "0011", "01"
 * Группа 2 и 3: min(2, 2) = 2 → "1100", "10"
 * Группа 3 и 4: min(2, 2) = 2 → "0011", "01"
 * Сумма: 2 + 2 + 2 = 6 ✓
 * <p>
 * Пример 2: s = "10101"
 * Группы: [1, 1, 1, 1, 1]
 * Соседние пары:
 * min(1, 1) = 1 → "10"
 * min(1, 1) = 1 → "01"
 * min(1, 1) = 1 → "10"
 * min(1, 1) = 1 → "01"
 * Сумма = 4 ✓
 * <p>
 * Почему это работает?
 * Любая подстрока, удовлетворяющая условиям, будет образована ровно из двух соседних групп:
 * Левая группа (все одинаковые символы)
 * Правая группа (все другие символы)
 * Она не может захватывать больше групп, потому что тогда символы перестанут быть сгруппированы.
 * <p>
 * Временная сложность
 * Проход по строке для создания групп: O(n)
 * <p>
 * Проход по группам: O(количество групп) ≤ O(n)
 * <p>
 * Итого: O(n), что отлично для n ≤ 10⁵
 * <p>
 * Пространственная сложность
 * Можно хранить массив длин групп: O(n)
 */
fun countBinarySubstrings(s: String): Int {
    // хранение длин групп повторяющихся чисел
    val groups = mutableListOf<Int>()
    var result = 0

    // индексы начала и конца группы повторяющихся символов
    var l = 0
    var r = 0

    // подсчитываем длину каждой группы повторяющихся чисел
    while (r < s.length) {
        // какие символы (0 или 1) в группе
        val firstChar = s[l]
        var length = 0

        // считаем количество символов в группе
        while (r < s.length && s[r] == firstChar) {
            length++
            r++
        }

        // добавляем длину группы
        groups.add(length)
        l = r
    }

    // берем каждую пару длин групп и берем меньшее из значений
    for (i in 0 until groups.size - 1) {
        val first = groups[i]
        val second = groups[i + 1]
        result += min(first, second)
    }

    return result
}