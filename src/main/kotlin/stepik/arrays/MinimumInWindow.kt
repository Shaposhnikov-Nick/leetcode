package stepik.arrays

/**
 3.10 Минимум в окне (на очереди)
 Задача: маленький отрезок, но с большим потенциалом

Вам дан массив целых чисел a и число k.
Рассмотрим некоторый подотрезок массива a. Его потенциалом назовём разницу между максимальным и минимальным числом на отрезке. Найдите отрезок минимальной длины такой, что его потенциал не меньшеk.

Входные данные

На первой строке длина массива n (1 ≤ n ≤ 3 10 5) и число k (1 ≤ k ≤ 10 9).
На второй строке массив a: n целых чисел от 1 до 10 9.

Выходные данные

Выведите длину минимального отрезка с потенциалом хотя бы k.
Если такого отрезка не существует, в качестве ответа выведите 0.

 РЕШЕНИЕ:
 
 Структуры данных: Используем ArrayDeque<Int> для хранения индексов элементов, а не самих значений. Это позволяет легко удалять элементы, когда сдвигаем левую границу.

 Поддержание минимума (minDeque):

 При добавлении нового элемента удаляем с конца все индексы, чьи значения ≥ нового.

 В начале дека всегда лежит индекс минимального элемента в текущем окне.

 Поддержание максимума (maxDeque):

 При добавлении удаляем с конца все индексы, чьи значения ≤ нового.

 В начале дека всегда лежит индекс максимального элемента.

 Два указателя:

 right движется в цикле, добавляя элементы.

 Внутренний while сжимает окно слева, как только потенциал становится ≥ k.

 Удаление при сдвиге left:

 Проверяем, не является ли удаляемый индекс первым в каждой деке. Если да — удаляем его оттуда.

 Сложность: O(n) времени и O(n) памяти в худшем случае (хотя деки обычно содержат не все элементы, а только полезные для экстремумов).

 Пример работы:
 Для массива [1, 5, 2, 8, 2] и k = 6:

 Окно [2, 8] даёт потенциал 6, длина 2 → ответ 2.

 Алгоритм найдёт это окно и попытается сжать его дальше, но не сможет, потому что [8] или [2] уже не дают нужного потенциала.
 */
fun main() {
    val (n, k) = readln().split(" ").map { it.toInt() }
    val nums = readln().split(" ").map { it.toInt() }

    // Деки для хранения индексов элементов
    val minDeque = ArrayDeque<Int>() // будет хранить индексы в возрастающем порядке значений
    val maxDeque = ArrayDeque<Int>() // будет хранить индексы в убывающем порядке значений

    var left = 0
    var ans = Long.MAX_VALUE

    for (right in 0 until n.toInt()) {
        // Добавляем новый элемент в деки
        // Для минимума: удаляем с конца все элементы, которые >= текущего
        while (minDeque.isNotEmpty() && nums[minDeque.last()] >= nums[right]) {
            minDeque.removeLast()
        }
        minDeque.addLast(right)

        // Для максимума: удаляем с конца все элементы, которые <= текущего
        while (maxDeque.isNotEmpty() && nums[maxDeque.last()] <= nums[right]) {
            maxDeque.removeLast()
        }
        maxDeque.addLast(right)

        // Пока потенциал >= k, пытаемся сжать окно слева
        while (minDeque.isNotEmpty() && maxDeque.isNotEmpty() &&
            nums[maxDeque.first()] - nums[minDeque.first()] >= k) {
            // Обновляем ответ
            val currentLen = right - left + 1
            if (currentLen < ans) {
                ans = currentLen.toLong()
            }

            // Удаляем левый элемент, если он есть в деках
            if (minDeque.first() == left) {
                minDeque.removeFirst()
            }
            if (maxDeque.first() == left) {
                maxDeque.removeFirst()
            }
            left++
        }
    }

    // Если ответ не был обновлён - такого отрезка нет
    println(if (ans == Long.MAX_VALUE) 0 else ans)
}