 * Дана строка, содержащая только символы ( и ). Определите максимальную глубину вложенности скобок в данном выражении.
 */

/**
 * Что такое глубина вложенности
 * Глубина вложенности — это максимальное количество открытых скобок, которые ещё не закрыты, встретившихся по ходу строки. Например:
 *
 * ()() → глубина 1 (в любой момент открыта максимум одна скобка)
 *
 * (()) → глубина 2 (внутри внешней скобки есть ещё одна)
 *
 * ((())) → глубина 3
 *
 * Идея решения
 * Нужно пройти по строке слева направо, ведя счётчик текущей глубины:
 *
 * Заводим две переменные:
 *
 * current — текущая глубина (сколько скобок сейчас открыто).
 *
 * max — максимальная глубина, которую мы видели.
 *
 * Идём по каждому символу строки:
 *
 * Если символ ( — увеличиваем current на 1. Затем сравниваем current с max и, если текущая глубина больше, обновляем max.
 *
 * Если символ ) — уменьшаем current на 1 (скобка закрылась).
 *
 * В конце ответ — это значение max.
 *
 * Почему это работает
 * Открывающая скобка увеличивает «уровень погружения», закрывающая — уменьшает.
 *
 * Максимум достигается именно в момент, когда мы открыли очередную скобку и ещё не закрыли её. Поэтому обновлять max логично сразу после увеличения current.
 *
 * Так как строка корректная (скобки сбалансированы), current в конце вернётся к 0, а по пути не уйдёт в минус.
 */
fun main() {
    val s = "((()))".toCharArray()
//    val s = readln().toCharArray()
    var current = 0
    var max = 0

    for (p in s){
        if (p == '('){
            current++
            max = maxOf(current, max)
        } else {
            current--
        }
    }

    print(max)
}