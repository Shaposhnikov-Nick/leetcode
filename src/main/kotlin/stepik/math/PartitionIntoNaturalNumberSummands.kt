package stepik.math

/**
 * 2.4 Рекурсия
 *
 * Разбиение на натуральные слагаемые (2 балла)
 *
 * Дано натуральное число N. Рассмотрим его разбиение на натуральные слагаемые. Два разбиения, отличающихся только порядком слагаемых,
 * будем считать за одно, поэтому можно считать, что слагаемые в разбиении упорядочены по невозрастанию.
 *
 * Формат ввода
 * Задано единственное число N. (N ≤ 40 )
 *
 * Формат вывода
 * Необходимо вывести все разбиения числа N на натуральные слагаемые в лексикографическом порядке.
 */
fun main() {
    val n = readln().toInt()
    val result = mutableListOf<Int>()
    partitionNumber(n, n, result)
}

/**
 * Логика решения задачи (алгоритм)
 * Чтобы решить эту задачу, нужно перебрать все варианты. Так как N ≤ 40, перебор всех вариантов (их около 40 000 для 40) вполне допустим.
 *
 * Лучший способ — рекурсия (поиск в глубину / DFS).
 *
 * Представьте, что вы строите разбиение по частям.
 *
 * Идея:
 * У нас есть:
 *
 * Оставшаяся сумма (rem), которую нужно разложить.
 *
 * Максимальное число, которое мы можем поставить сейчас (max_allowed). Оно нужно, чтобы соблюдать порядок невозрастания. Если мы поставили число 5, то следующее число не может быть больше 5, иначе мы получим дубликат.
 *
 * Алгоритм:
 *
 * Начинаем с rem = N, max_allowed = N, пустой список текущего разбиения.
 *
 * На каждом шаге мы выбираем очередное слагаемое x.
 *
 * Оно должно быть от 1 до max_allowed (чтобы порядок не нарушался).
 *
 * Мы вычитаем его из остатка: new_rem = rem - x.
 *
 * Если new_rem == 0 — мы нашли разбиение! Запоминаем его.
 *
 * Если new_rem > 0 — идем глубже, но теперь максимальное число для следующего шага будет min(x, new_rem) (нельзя взять больше, чем осталось, и больше, чем предыдущее число).
 *
 * Чтобы получить лексикографический порядок, мы должны перебирать числа x в цикле от 1 до max_allowed (по возрастанию).
 *
 *
 */
fun partitionNumber(remain: Int, maxAllowed: Int, current: MutableList<Int>) {
    // Базовый случай: разложили всё число
    if (remain == 0) {
        println(current.joinToString(" "))
        return
    }

    // Перебираем возможные следующие слагаемые от 1 до maxAllowed
    // min(maxAllowed, remain) - нельзя взять больше, чем осталось
    for (x in 1..minOf(maxAllowed, remain)) {
        current.add(x)
        partitionNumber(remain - x, x, current) // следующее число не может быть больше x
        current.removeAt(current.size - 1) // backtracking
    }
}