package stepik.math

/**
 * 2.3 Анализ сложности алгоритмов. Введение в O-нотацию
 * Кинотеатр (1 балл)
 * N программистов и M программисток пошли в кинотеатр и купили билеты на подряд идущие места в одном ряду. Напишите программу,
 * которая выдаст, как нужно сесть программистам и программисткам, чтобы рядом с каждым программистом сидела хотя бы одна программистка,
 * а рядом с каждой программисткой --- хотя бы один программист.
 *
 * Формат ввода
 *
 * Вводятся два числа - N и M (оба числа натуральные, не превосходящие 100).
 *
 * Формат вывода
 *
 * Выведите какую-нибудь строку, в которой будет ровно N символов B (обозначающих программистов) и M символов G (обозначающих программисток),
 * удовлетворяющую условию задачи. Пробелы между символами или после всех символов выводить не нужно. Если рассадить программистов
 * и программисток согласно условию задачи невозможно, выведите строку NO SOLUTION.
 *
 * Примечание
 *
 * Обратите внимание, что решение с полным перебором вариантов рассадки может не пройти по времени.
 *
 * Тестовые данные
 *

 * Входные данные
 * Выходные данные
 * 5 5
 * BGBGBGBGBG
 *
 * 5 3
 * BGBBGBBG
 *
 * 100 1
 * NO SOLUTION
 */

/**
 * ## Идея решения
 *
 * Все блоки нужно строить так, чтобы **каждый блок сам по себе** уже удовлетворял условию — тогда неважно, как блоки стыкуются
 * друг с другом, потому что если у буквы уже есть подходящий сосед внутри своего блока, дополнительные соседи снаружи ей не мешают
 * (условие требует "хотя бы одного", а не "ровно одного").
 *
 * Используются два типа "кирпичиков":
 *
 * - **`"BGB"`** — 2 буквы B и 1 буква G. Внутри блока: `B G B`. У каждой B есть сосед G (у первой — справа, у второй — слева),
 * у G — целых два соседа B. Условие выполнено для всех трёх символов автономно.
 * - **`"BG"`** — 1 буква B и 1 буква G. У B сосед G, у G сосед B — тоже всё хорошо.
 *
 * Раз каждый блок "самодостаточен", их можно клеить друг за другом в любом порядке — на стыках могут получиться `BB` или `GG`,
 * но это не страшно: обе буквы там уже "прикрыты" изнутри своего блока.
 *
 * ## Подсчёт количества блоков (случай n ≥ m, т.е. B ≥ G)
 *
 * Нужно распределить весь запас B и G между этими двумя видами кирпичиков.
 *
 * Пусть используется `k` штук `"BGB"` и `t` штук `"BG"`. Тогда:
 * - всего B: `2k + t = n`
 * - всего G: `k + t = m`
 *
 * Вычитая одно уравнение из другого: `k = n - m`, тогда `t = m - k = m - (n-m) = 2m - n`.
 *
 * Именно поэтому в коде:
 * ```kotlin
 * repeat(n - m) { append("BGB") }   // k блоков "BGB"
 * repeat(2 * m - n) { append("BG") } // t блоков "BG"
 * ```
 *
 * Чтобы `t = 2m - n` было неотрицательным, нужно `n ≤ 2m` — это как раз то условие, что проверяется в самом начале (`n > 2 * m` → NO SOLUTION).
 * А `k = n - m ≥ 0` обеспечивается веткой `n >= m`.
 *
 * ## Случай m > n (G больше)
 *
 * Полностью симметрично: строим блоки `"GBG"` (2 буквы G, 1 B — "лишние" G прячем сюда) и `"BG"`:
 * - `k = m - n` блоков `"GBG"` съедают избыток G,
 * - `t = 2n - m` блоков `"BG"` разбирают остаток.
 *
 * ```kotlin
 * repeat(m - n) { append("GBG") }
 * repeat(2 * n - m) { append("BG") }
 * ```
 *
 * Условие `m ≤ 2n` проверяется как `m > 2 * n` → `NO SOLUTION`.
 *
 * ## Проверка условия существования решения
 *
 * `n > 2*m || m > 2*n` — это ровно то же самое, что раньше выводилось как `max(n,m) ≤ 2·min(n,m)`, только записанное через отрицание.
 * Плюс проверка `n == 0 || m == 0`: если кого-то нет вообще, а другой при этом есть, рассадить с соблюдением условия невозможно (некому быть соседом).
 *
 * ## Пример: n=5, m=3
 *
 * - `n >= m` → используем первую ветку.
 * - `k = n - m = 2` блока `"BGB"`.
 * - `t = 2m - n = 1` блок `"BG"`.
 * - Итог: `"BGB" + "BGB" + "BG"` = `BGBBGBBG` — 5 букв B, 3 буквы G, ровно как в тесте.
 *
 * Проверка соседей: `B G B B G B B G`
 * - B(1): сосед G ✓
 * - G(2): соседи B,B ✓
 * - B(3): сосед G ✓ (слева)
 * - B(4): сосед G ✓ (справа)
 * - G(5): соседи B,B ✓
 * - B(6): сосед G ✓ (слева)
 * - B(7): сосед G ✓ (справа)
 * - G(8): сосед B ✓
 *
 * Всё сходится — это решение проще и элегантнее моего исходного варианта со "слотами", хотя по сути оба подхода опираются на одну и ту же идею:
 * разбить строку на самодостаточные блоки длины ≤ 3, не примыкающие "неудачно" друг к другу.
 */
fun main() {
    val (n, m) = readln().split(" ").map { it.toInt() }

    val result = if (n == 0 || m == 0 || n > m * 2 || m > n * 2) {
        "NO SOLUTION"
    } else if (n > m) {
        buildString {
            repeat(n - m) {
                append("BGB")
            }

            repeat(2 * m - n) {
                append("BG")
            }
        }
    } else {
        buildString {
            repeat(m - n) {
                append("GBG")
            }

            repeat(2 * n - m) {
                append("BG")
            }
        }
    }
    print(result)
}