/**
 * 2.4 Рекурсия
 *
 * Рекурсивный перевод (2 балла)
 *
 * Напишите рекурсивную процедуру для перевода десятичного числа в P-ичную систему счисления.
 *
 * В данной задаче запрещено использовать циклы и массивы.
 *
 * Входные данные
 *
 * На вход программе сначала подается значение P(1<P<10), а во второй строке — десятичное число.
 *
 * Выходные данные
 *
 * Вывод осуществляйте следующим образом: сначала выведите введённое число в десятичной системе счисления, за ним укажите его систему счисления в круглых скобках, то есть
 * (10), затем поставьте знак "=", после чего выведете результат работы вашей программы — число в
 * P-ичной системе счисления, за ним укажите его систему счисления в круглых скобках. Весь вывод осуществляется без пробелов.
 */
fun main() {
    val p = readln().toInt()
    val num = readln().toInt()
    val result = mutableListOf<Int>()

    conversion(num, p, result)

    print("$num(10)=${result.joinToString("")}($p)")
}

/**
 * Для перевода числа из десятичной системы в любую другую (с основанием от 2 до 36) используется метод последовательного деления на основание новой системы.
 *
 * Вот пошаговая инструкция:
 *
 * Шаг 1: Делите нацело
 * Разделите исходное десятичное число на основание новой системы счисления (например, на 2, 8 или 16).
 * Шаг 2: Записывайте остатки
 * Запишите остаток от деления (он всегда должен быть меньше основания). Это будет младшая цифра (последняя) в новом числе.
 * Шаг 3: Повторяйте с частным
 * Возьмите полученное частное (целую часть от деления), снова разделите его на основание и снова запишите остаток.
 * Шаг 4: Конец
 * Продолжайте делить до тех пор, пока частное не станет равно 0.
 * Шаг 5: Соберите результат
 * Запишите все остатки в обратном порядке (снизу вверх). Первый остаток, который вы записали, будет самой правой цифрой, а последний — самой левой.
 *
 * Пример 1: Перевод числа 13 в двоичную систему (основание 2)
 * 13 ÷ 2 = 6 (остаток 1)
 * 6 ÷ 2 = 3 (остаток 0)
 * 3 ÷ 2 = 1 (остаток 1)
 * 1 ÷ 2 = 0 (остаток 1)
 * Читаем остатки снизу вверх: 1101.
 * Ответ: 13₁₀ = 1101₂
 *
 * Пример 2: Перевод числа 125 в восьмеричную систему (основание 8)
 * 125 ÷ 8 = 15 (остаток 5)
 * 15 ÷ 8 = 1 (остаток 7)
 * 1 ÷ 8 = 0 (остаток 1)
 * Читаем снизу вверх: 175.
 * Ответ: 125₁₀ = 175₈
 *
 * Пример 3: Перевод числа 255 в шестнадцатеричную систему (основание 16)
 * 255 ÷ 16 = 15 (остаток 15 — это буква F)
 * 15 ÷ 16 = 0 (остаток 15 — это буква F)
 * Читаем снизу вверх: FF.
 * Ответ: 255₁₀ = FF₁₆
 *
 * Важное замечание про буквы
 * В системах с основанием больше 10 (например, 16-ричная) для остатков 10, 11, 12, 13, 14, 15 используются латинские буквы:
 * 10 = A
 * 11 = B
 * 12 = C
 * 13 = D
 * 14 = E
 * 15 = F
 */
fun conversion(value: Int, p: Int, result: MutableList<Int>) {
    if (value == 0) return

    // считаем следующее число
    val newValue = value / p
    // остаток от деления записываем в результат
    val digit = value % p
    result.add(0,digit)

    // вызываем рекурсивно для следующего числа
    conversion(newValue, p, result)
}