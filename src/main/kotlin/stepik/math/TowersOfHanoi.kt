 */
fun main() {
    val n = readln().toInt()
    moveDisks(n, 1, 3, 2)
}

/**
 * Логика решения (в 3 пунктах)
 *
 * Разбей задачу: Чтобы переместить n дисков со стержня 1 на стержень 3:
 * Сначала перемести верхние n-1 дисков на вспомогательный стержень 2
 * Потом перемести самый большой диск с 1 на 3
 * Затем перемести n-1 дисков со стержня 2 на стержень 3
 *
 * Рекурсия: Пункты 1 и 3 — это те же самые задачи, но с n-1 дисками и другими стержнями. Функция вызывает саму себя, пока не останется 1 диск.
 *
 * Базовый случай: Когда диск один — просто перемещаем его с текущего стержня на целевой. Дальше не делим.
 *
 * Визуальная схема для n=3
 * text
 * Перенести 3 диска с 1 на 3
 *     │
 *     ├─ Перенести 2 диска с 1 на 2 (вспомогательный)
 *     │      ├─ Перенести 1 диск с 1 на 3
 *     │      ├─ Перенести 1 диск с 1 на 2
 *     │      └─ Перенести 1 диск с 3 на 2
 *     │
 *     ├─ Перенести 1 диск с 1 на 3 (САМЫЙ БОЛЬШОЙ)
 *     │
 *     └─ Перенести 2 диска с 2 на 3
 *            ├─ Перенести 1 диск с 2 на 1
 *            ├─ Перенести 1 диск с 2 на 3
 *            └─ Перенести 1 диск с 1 на 3
 *
 * Суть одной фразой
 * "Чтобы перенести пирамиду, сначала убери верхушку, перенеси основание, потом верни верхушку обратно"
 *
 * И так повторяешь, пока не дойдёшь до одного диска, который переносится за один ход.
 *
 * Количество ходов
 * 2^n - 1 (для 3 дисков → 7 ходов, для 20 → 1 048 575 ходов)
 *
 * Почему именно такая нумерация в вызове?
 * В основной программе мы пишем Ханой(n, 1, 3, 2):
 *
 * 1 — откуда начинаем (стержень 1)
 * 3 — куда должны прийти (стержень 3)
 * 2 — вспомогательный стержень
 *
 * Внутри функции:
 * Первый рекурсивный вызов: Ханой(n-1, начальный, вспомогательный, конечный) — меняем местами конечный и вспомогательный
 * Затем выводим перемещение самого большого диска
 * Второй рекурсивный вызов: Ханой(n-1, вспомогательный, конечный, начальный) — меняем местами начальный и вспомогательный
 * Это классическая рекурсивная схема, которая гарантирует правильное решение для любого N от 1 до 20.
 */
fun moveDisks(n: Int, from: Int, to: Int, helper: Int) {
    if (n == 1) {
        println("Переместите диск с $from на $to")
        return
    }

    // Шаг 1: Переместить n-1 дисков с начального на вспомогательный
    // (используя конечный как временный)
    moveDisks(n - 1, from, helper, to)

    // Шаг 2: Переместить самый большой диск с начального на конечный
    println("Переместите диск с $from на $to")

    // Шаг 3: Переместить n-1 дисков с вспомогательного на конечный
    // (используя начальный как временный)
    moveDisks(n - 1, helper, to, from)
}