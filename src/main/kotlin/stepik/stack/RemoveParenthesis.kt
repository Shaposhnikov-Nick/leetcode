package stepik.stack

/**
 * 3.5 Стек
 *
 * Удалите скобки* (2 балла)
 *
 * Дана строка, составленная из круглых скобок. Определите, какое наименьшее количество символов необходимо удалить из этой строки, чтобы оставшиеся символы образовывали правильную скобочную последовательность.
 *
 * Входные данные
 *
 * Во входном файле записана строка из круглых скобок. Длина строки не превосходит 10 в 9 символов.
 *
 * Выходные данные
 *
 * Выведите единственное целое число — ответ на поставленную задачу.
 */
/**
 * Проходим по всем скобкам
 * если скобка открывающая "(", то добавляем ее в стек
 * если скобка закрывающая, то достаем из стека последнюю добавленную скобку. Если стек пуст, значит эта скобка лишняя.
 * также в конце проверяем, что в стеке могут остаться незакрытые скобки, их тоже нужно удалить
 */
fun main() {
    val s = readln().split("")
    val stack = ArrayDeque<String>()
    var deletedCount = 0

    // Проходим по всем скобкам
    for (p in s) {
        // если скобка открывающая "(", то добавляем ее в стек
        if (p == "(") stack.addLast(p)
        // если скобка закрывающая, то достаем из стека последнюю добавленную скобку. Если стек пуст, значит эта скобка лишняя.
        if (p == ")") {
            val last = stack.removeLastOrNull()
            if (last == null) {
                deletedCount++
            }
        }
    }

    // в ответе считаем сумму найденных лмшних скобок и оставшихся не закрытых скобок в стеке
    println(deletedCount + stack.size)
}